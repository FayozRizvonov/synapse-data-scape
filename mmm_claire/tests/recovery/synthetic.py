"""
Synthetic MMM data with known parameters.

Every number this pipeline reports about the real dataset — r2, contributions, ROI, VRR
— is a statement about parameters nobody can check, because the true parameters of a
real market are not observable. So "did the model train properly?" has never been
answerable from the real data alone. It is answerable here: generate the target from
known coefficients and ask whether the posterior finds them again.

The generator deliberately uses the model's OWN forward computation (the same one
`src/validation/holdout.py` mirrors in NumPy) at the model's own functional form:
geometric adstock, then Michaelis-Menten saturation, then a linear sum. There is
therefore ZERO misspecification by construction. That is the point — it makes the test
sharp. A model that cannot recover parameters from data generated by its own equations
is not failing because reality is complicated; it is failing because the parameters are
not identified at this sample size, because a prior is fighting the likelihood, or
because a transform has destroyed the signal before the likelihood ever sees it.

The truth respects every hard constraint the model imposes, so a miss is informative
rather than a foregone conclusion:

  * beta_media > 0            -- the model forces positivity via softplus
  * upper > mid > lower       -- the funnel hierarchy orders the prior means
  * gamma in [0.3, 2.0]       -- clipped (gamma_cap = 2.0 for monthly/low_data)
  * theta in [0.01, 0.5)      -- clipped (theta_cap = 0.5 for monthly/low_data)

`theta` and `gamma` are the cleanest targets in the whole set because they sit inside
the nonlinearity and are therefore scale-free: unlike the betas they need no affine
correction, so a miss on them cannot be blamed on bookkeeping.

The one thing that varies between runs is how media is scaled before it reaches the
model (`media_scale`). Everything else is held fixed, so the experiment changes one
variable at a time.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field, asdict
from pathlib import Path

import numpy as np
import pandas as pd

# The model reads monthly seasonality on a 12-period cycle (pymc_mmm.py), and the demo
# dataset is monthly, so the generator is monthly too.
PERIOD = 12.0

REGION = "national"
SUB_BRAND = "dovato"


# ---------------------------------------------------------------------------
# the truth
# ---------------------------------------------------------------------------

@dataclass
class Truth:
    """
    Known parameters, in the units the model fits (standardised target).

    Channel levels mirror the real dovato dataset's activity magnitudes, because the
    whole question about media scaling only exists at realistic magnitudes: a channel
    running at ~14,500 mass emails a month behaves very differently under
    `x / (gamma + x)` with `gamma <= 2` than one running at 34 webinars.
    """

    # name -> funnel subtype. The model derives its beta ordering from this.
    subtype: dict = field(default_factory=lambda: {
        "clm_call":     "upper",
        "non_clm_call": "mid",
        "webinar":      "mid",
        "mass_email":   "lower",
        "email_1to1":   "lower",
        "phone_call":   "lower",
    })

    # Monthly activity level, matched to the real data's means.
    level: dict = field(default_factory=lambda: {
        "clm_call":     2100.0,
        "non_clm_call": 1400.0,
        "webinar":        34.0,
        "mass_email":  14500.0,
        "email_1to1":    695.0,
        "phone_call":    285.0,
    })

    # Media response. Ordered to respect the funnel: upper > mid > lower.
    beta_media: dict = field(default_factory=lambda: {
        "clm_call":     0.80,   # upper
        "non_clm_call": 0.50,   # mid
        "webinar":      0.45,   # mid
        "mass_email":   0.25,   # lower
        "email_1to1":   0.20,   # lower
        "phone_call":   0.15,   # lower
    })

    # Carryover. Spread across the recoverable band so a single cap artefact cannot
    # masquerade as recovery -- if every truth sat at 0.3 then a posterior pinned at
    # 0.3 would look like a pass.
    theta: dict = field(default_factory=lambda: {
        "clm_call":     0.40,
        "non_clm_call": 0.30,
        "webinar":      0.20,
        "mass_email":   0.10,
        "email_1to1":   0.35,
        "phone_call":   0.05,
    })

    # Half-saturation point, inside the [0.3, 2.0] clip.
    gamma: dict = field(default_factory=lambda: {
        "clm_call":     1.20,
        "non_clm_call": 0.80,
        "webinar":      1.50,
        "mass_email":   0.50,
        "email_1to1":   1.00,
        "phone_call":   0.40,
    })

    # Controls. `comp1` is a continuous competitor index; `ex_1` and `ex_2` are binary
    # event dummies, laid out like the real ones (ex_1 recurs annually, ex_2 is a
    # sustained four-month block) -- this is what tests whether declaring an event as
    # `type=control` in info.csv actually recovers its effect.
    beta_control: dict = field(default_factory=lambda: {
        "comp1": -0.02,
        "ex_1":   0.30,
        "ex_2":  -0.20,
    })

    intercept: float = 0.0
    beta_trend: float = 0.02
    seas_sin: float = 0.25
    seas_cos: float = -0.18
    sigma: float = 0.25

    # Cost per activity, used to synthesise spend.csv. Spend matters even for a pure
    # recovery test: `build_pymc_model` shifts the media prior means by
    # `0.6 * log(spend_share)`, so the shares have to be realistic or the test would
    # be measuring recovery under a prior the production model never uses.
    cost_per_unit: dict = field(default_factory=lambda: {
        "clm_call":     130.0,
        "non_clm_call":  85.0,
        "webinar":     1800.0,
        "mass_email":     0.9,
        "email_1to1":    12.0,
        "phone_call":    40.0,
    })

    @property
    def media(self) -> list:
        # build_tensors sorts media alphabetically; match that everywhere so the
        # comparison never relies on dict ordering.
        return sorted(self.beta_media)

    @property
    def controls(self) -> list:
        return sorted(self.beta_control)

    def vec(self, attr: str, names: list) -> np.ndarray:
        return np.array([getattr(self, attr)[n] for n in names], dtype=float)


# ---------------------------------------------------------------------------
# regressors
# ---------------------------------------------------------------------------

def _activity(rng, T: int, level: float, phase: float) -> np.ndarray:
    """
    One channel's monthly activity: an AR(1) in logs plus a phase-shifted annual
    swing, floored at 5% of the level.

    The phase shift is the part that matters. Six channels driven by the same seasonal
    term would be collinear, and collinear regressors are unidentifiable for reasons
    that have nothing to do with the model under test -- the recovery run would fail
    and tell us only that we built a bad design matrix. Spreading the phases keeps the
    pairwise correlations low; `run_recovery.py` reports the worst one so the design is
    audited rather than assumed.
    """
    rho, sd = 0.45, 0.30
    z = np.zeros(T)
    eps = rng.normal(0.0, 1.0, T)
    for t in range(T):
        z[t] = eps[t] if t == 0 else rho * z[t - 1] + eps[t]
    z = z / max(z.std(), 1e-9)

    swing = 0.45 * np.sin(2 * np.pi * np.arange(T) / PERIOD + phase)
    x = level * np.exp(sd * z + swing - 0.5 * sd ** 2)
    return np.maximum(x, level * 0.05)


def _controls(rng, T: int) -> dict:
    """
    comp1 continuous; ex_1 / ex_2 binary dummies shaped like the real dataset's.

    Left at their real magnitudes on purpose: `x_control_data` receives X_control
    unscaled, so comp1 arriving at ~53 is a production condition, not a detail of the
    simulation.
    """
    comp1 = 50.0 + 5.0 * rng.normal(0.0, 1.0, T).cumsum() / np.sqrt(T)

    ex_1 = np.zeros(T)
    for t in range(4, T, 12):            # annually recurring, one month each time
        ex_1[t] = 1.0

    ex_2 = np.zeros(T)
    lo, hi = 9, min(13, T)               # one sustained four-month block
    ex_2[lo:hi] = 1.0

    return {"comp1": comp1, "ex_1": ex_1, "ex_2": ex_2}


# ---------------------------------------------------------------------------
# forward model -- mirrors pymc_mmm.build_pymc_model
# ---------------------------------------------------------------------------

def forward(X_media: np.ndarray, X_control: np.ndarray, truth: Truth) -> tuple:
    """
    mu = intercept + trend + season + control_effect + media_effect

    Mirrors `build_pymc_model` term for term, including the `clip(x, 1e-6, 1e6)` before
    saturation. Returns ``(mu, x_sat)``; `x_sat` is handed back so the caller can report
    how much time-varying signal actually survives the transform.
    """
    T, C = X_media.shape
    media = truth.media
    theta = truth.vec("theta", media)
    gamma = truth.vec("gamma", media)
    beta_m = truth.vec("beta_media", media)

    # geometric adstock: x_ad[t] = x[t] + theta * x_ad[t-1]
    x_ad = np.empty((T, C))
    prev = np.zeros(C)
    for t in range(T):
        prev = X_media[t] + theta * prev
        x_ad[t] = prev

    x_safe = np.clip(x_ad, 1e-6, 1e6)
    x_sat = x_safe / (gamma + x_safe)

    t_idx = np.arange(T)
    mu = (
        truth.intercept
        + truth.beta_trend * t_idx
        + truth.seas_sin * np.sin(2 * np.pi * t_idx / PERIOD)
        + truth.seas_cos * np.cos(2 * np.pi * t_idx / PERIOD)
        + X_control @ truth.vec("beta_control", truth.controls)
        + x_sat @ beta_m
    )
    return mu, x_sat


# ---------------------------------------------------------------------------
# generation
# ---------------------------------------------------------------------------

def generate(
    out_dir: Path,
    periods: int = 33,
    media_scale: str = "raw",
    seed: int = 20261104,
    out_mean: float = 80_000.0,
    out_std: float = 15_000.0,
) -> dict:
    """
    Write data.csv / info.csv / spend.csv plus truth.json into `out_dir`.

    `media_scale` is the single manipulated variable:

      ``raw``   activity as counts, exactly what the pipeline feeds the model today
      ``mean``  activity divided by its own mean, so each channel averages 1.0

    It is NOT a cosmetic choice. Saturation is `x / (gamma + x)` with gamma clipped to
    at most 2.0, so the transform only responds where x is of order gamma. At raw
    counts in the thousands every period maps to ~0.9999 and the regressor becomes a
    constant; divided by its mean, the same series lands in the responsive part of the
    curve. `run_recovery.py` quantifies the difference rather than asserting it.

    On the affine correction: the generator produces a standardised `mu`, scales it to
    realistic volume units for the CSV, and `build_tensors` then re-standardises using
    that series' own empirical moments. The round trip is affine, so the truth has to be
    mapped into the space the model actually fits -- `(a, b)` below carries exactly
    that, and `out_mean` / `out_std` cancel out of it entirely.
    """
    if media_scale not in ("raw", "mean"):
        raise ValueError(f"media_scale must be 'raw' or 'mean', got {media_scale!r}")

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(seed)
    truth = Truth()
    media, controls = truth.media, truth.controls
    T = periods

    dates = pd.date_range("2023-01-01", periods=T, freq="MS")

    # --- regressors -------------------------------------------------------
    phases = np.linspace(0.0, 2.0 * np.pi, len(media), endpoint=False)
    activity = {
        m: _activity(rng, T, truth.level[m], ph) for m, ph in zip(media, phases)
    }

    # Spend tracks activity at a per-unit cost. Written from the RAW activity whatever
    # `media_scale` does to the modelled regressor, because spend is money and does not
    # rescale when the analyst changes units.
    spend = {m: activity[m] * truth.cost_per_unit[m] for m in media}

    if media_scale == "mean":
        modelled = {m: activity[m] / activity[m].mean() for m in media}
    else:
        modelled = {m: activity[m].copy() for m in media}

    ctrl = _controls(rng, T)

    X_media = np.column_stack([modelled[m] for m in media])
    X_control = np.column_stack([ctrl[c] for c in controls])

    # --- target -----------------------------------------------------------
    mu, x_sat = forward(X_media, X_control, truth)
    y_std_units = mu + rng.normal(0.0, truth.sigma, T)
    y = y_std_units * out_std + out_mean

    # The affine map into the space build_tensors will fit. ddof=0 matches Y.std().
    a = float(y_std_units.mean())
    b = float(y_std_units.std())

    # --- CSVs -------------------------------------------------------------
    rows = []

    def emit(variable, values):
        for d, v in zip(dates, values):
            rows.append({
                "date": d.strftime("%Y-%m-%d"),
                "region": REGION,
                "sub_brand": SUB_BRAND,
                "variable": variable,
                "value": float(v),
            })

    emit("volume", y)
    for m in media:
        emit(m, modelled[m])
    for c in controls:
        emit(c, ctrl[c])

    pd.DataFrame(rows).to_csv(out_dir / "data.csv", index=False)

    info = [{
        "variable": "volume", "type": "kpi_volume", "subtype": "na",
        "variation_level": "geo_sub_brand", "expected_sign": "na",
    }]
    for m in media:
        info.append({
            "variable": m, "type": "media", "subtype": truth.subtype[m],
            "variation_level": "geo_sub_brand", "expected_sign": "positive",
        })
    for c in controls:
        info.append({
            "variable": c, "type": "control", "subtype": "na",
            "variation_level": "geo_sub_brand", "expected_sign": "na",
        })
    pd.DataFrame(info).to_csv(out_dir / "info.csv", index=False)

    pd.DataFrame([
        {
            "date": d.strftime("%Y-%m-%d"), "region": REGION,
            "sub_brand": SUB_BRAND, "media": m, "spend": float(s),
        }
        for m in media
        for d, s in zip(dates, spend[m])
    ]).to_csv(out_dir / "spend.csv", index=False)

    # --- how much signal survived the transform ---------------------------
    # Reported per channel as the ratio of the saturated regressor's coefficient of
    # variation to the raw series'. Near zero means the likelihood is being shown a
    # constant, and no amount of sampling can recover a coefficient on a constant.
    signal = {}
    for i, m in enumerate(media):
        raw = modelled[m]
        raw_cv = float(raw.std() / max(raw.mean(), 1e-12))
        sat_cv = float(x_sat[:, i].std() / max(x_sat[:, i].mean(), 1e-12))
        signal[m] = {
            "raw_cv": raw_cv,
            "sat_cv": sat_cv,
            "sat_mean": float(x_sat[:, i].mean()),
            "signal_kept": float(sat_cv / raw_cv) if raw_cv > 0 else float("nan"),
        }

    # Worst pairwise correlation among the saturated regressors, so a recovery failure
    # caused by our own design matrix is visible instead of being blamed on the model.
    with np.errstate(invalid="ignore"):
        corr = np.corrcoef(x_sat, rowvar=False)
    off = corr[~np.eye(len(media), dtype=bool)]
    off = off[np.isfinite(off)]

    meta = {
        "periods": T,
        "media_scale": media_scale,
        "seed": seed,
        "affine": {"a": a, "b": b},
        "truth": asdict(truth),
        "variance_share": {
            "mu": float(mu.var()),
            "noise": float(truth.sigma ** 2),
            "r2_ceiling": float(mu.var() / (mu.var() + truth.sigma ** 2)),
        },
        "signal": signal,
        "max_abs_corr_saturated": float(np.abs(off).max()) if off.size else 0.0,
    }
    (out_dir / "truth.json").write_text(json.dumps(meta, indent=2))
    return meta


def fitted_truth(meta: dict) -> dict:
    """
    Map the generating parameters into the space the model fits.

    `build_tensors` standardises the target, which is an affine transform, so the
    intercept shifts and every slope divides by `b`. `theta` and `gamma` live inside the
    nonlinearity and are untouched -- which is precisely why they are the parameters to
    read first when judging a recovery run.
    """
    t = meta["truth"]
    a, b = meta["affine"]["a"], meta["affine"]["b"]
    media = sorted(t["beta_media"])
    controls = sorted(t["beta_control"])

    out = {
        "intercept": (t["intercept"] - a) / b,
        "beta_trend": t["beta_trend"] / b,
        "seasonality_sin": t["seas_sin"] / b,
        "seasonality_cos": t["seas_cos"] / b,
        "sigma": t["sigma"] / b,
    }
    for m in media:
        out[f"beta_media[{m}]"] = t["beta_media"][m] / b
        out[f"theta_media[{m}]"] = t["theta"][m]      # scale-free
        out[f"gamma_media[{m}]"] = t["gamma"][m]      # scale-free
    for c in controls:
        out[f"beta_control[{c}]"] = t["beta_control"][c] / b
    return out
